import { useCallback, useEffect, useState } from "react";
import { motion } from "framer-motion";
import { Sparkles, RefreshCw } from "lucide-react";
import { explain } from "../services/api";
import { levelColor } from "../utils/risk";

function Typewriter({ text }) {
  const [n, setN] = useState(0);

  useEffect(() => {
    setN(0);
    const timer = setInterval(() => {
      setN((v) => {
        if (v >= text.length) {
          clearInterval(timer);
          return v;
        }
        return v + 2;
      });
    }, 18);
    return () => clearInterval(timer);
  }, [text]);

  return (
    <>
      {text.slice(0, n)}
      {n < text.length && (
        <span className="ml-0.5 inline-block h-4 w-0.5 animate-pulse bg-aegis-300 align-middle" />
      )}
    </>
  );
}

export default function ExplainPanel({ zone }) {
  const [ai, setAi] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const color = levelColor(zone.level);

  const load = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      setAi(await explain(zone.zoneId));
    } catch (err) {
      setError(err.userMessage || err.message);
    } finally {
      setLoading(false);
    }
  }, [zone.zoneId]);

  useEffect(() => {
    load();
  }, [load]);

  return (
    <div className="glass p-6">
      <div className="flex items-center justify-between">
        <h3 className="flex items-center gap-2 font-display text-lg font-semibold text-white">
          <Sparkles className="h-5 w-5 text-violet-glow" />
          Why this score?
        </h3>
        <button onClick={load} disabled={loading} className="btn-ghost !px-3 !py-1.5 text-xs">
          <RefreshCw className={`h-3.5 w-3.5 ${loading ? "animate-spin" : ""}`} />
          Regenerate
        </button>
      </div>

      <div className="mt-4 min-h-[88px] rounded-xl bg-white/5 p-4 text-sm leading-relaxed text-slate-200 ring-1 ring-white/10">
        {loading && (
          <div className="space-y-2">
            <div className="skeleton h-3 w-full" />
            <div className="skeleton h-3 w-5/6" />
            <div className="skeleton h-3 w-2/3" />
          </div>
        )}
        {!loading && error && <p className="text-risk-critical">{error}</p>}
        {!loading && ai && (
          <>
            <Typewriter text={ai.explanation} />
            <p className="mt-3 text-[11px] uppercase tracking-wider text-slate-500">
              {ai.source === "groq" ? "Generated by Groq AI" : "Rule-based summary"}
            </p>
          </>
        )}
      </div>

      <h4 className="mt-6 text-sm font-semibold text-slate-300">Contributing factors</h4>
      <div className="mt-3 space-y-4">
        {zone.factors.map((f, i) => (
          <div key={f.key}>
            <div className="flex items-center justify-between text-sm">
              <span className="text-slate-300">{f.label}</span>
              <span className="text-slate-400">
                <span className="font-semibold text-white">{f.contribution}</span> / {f.weight}
              </span>
            </div>
            <div className="mt-1.5 h-2 overflow-hidden rounded-full bg-white/10">
              <motion.div
                className="h-full rounded-full"
                style={{ background: `linear-gradient(90deg, ${color}99, ${color})` }}
                initial={{ width: 0 }}
                animate={{ width: `${(f.contribution / f.weight) * 100}%` }}
                transition={{ duration: 0.8, delay: i * 0.07, ease: "easeOut" }}
              />
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}